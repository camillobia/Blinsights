CREATE TABLE IF NOT EXISTS upload_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    enviado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    total_linhas INTEGER NOT NULL,
    linhas_validas INTEGER NOT NULL,
    mensagem TEXT
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
    lote_id BIGINT PRIMARY KEY REFERENCES upload_lote(id) ON DELETE CASCADE,
    gerado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    resultado JSON NOT NULL
);

