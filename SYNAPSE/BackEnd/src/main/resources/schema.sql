-- Schema único do Blinsights. Executado pelo Spring a cada inicialização
-- (spring.sql.init.mode=always), por isso tudo usa IF NOT EXISTS.
-- O Hibernate não cria tabelas (ddl-auto=none); o Python usa as mesmas tabelas.

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha VARCHAR(100) NOT NULL,
    matricula VARCHAR(30),
    turma VARCHAR(60),
    perfil VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
);

CREATE TABLE IF NOT EXISTS upload_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    enviado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    total_linhas INTEGER NOT NULL,
    linhas_validas INTEGER NOT NULL,
    mensagem TEXT
);

CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254),
    segmento VARCHAR(100),
    consultor_id BIGINT,
    lote_id BIGINT REFERENCES upload_lote(id),
    codigo_cliente VARCHAR(50),
    nome_cliente VARCHAR(200),
    consultor VARCHAR(120),
    nivel_cliente VARCHAR(20),
    faturamento_anual NUMERIC(18, 2),
    cidade VARCHAR(120),
    uf VARCHAR(10),
    data_contratacao DATE,
    mes_contratacao VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS contrato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inicio DATE,
    data_fim DATE,
    valor NUMERIC(18, 2),
    cliente_id BIGINT REFERENCES cliente(id),
    servico_id BIGINT,
    lote_id BIGINT REFERENCES upload_lote(id),
    servicos_contratados TEXT,
    data_contratacao DATE
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
    lote_id BIGINT PRIMARY KEY REFERENCES upload_lote(id) ON DELETE CASCADE,
    gerado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    resultado JSON NOT NULL
);

