CREATE TABLE IF NOT EXISTS upload_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    enviado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    total_linhas INTEGER NOT NULL,
    linhas_validas INTEGER NOT NULL,
    mensagem TEXT
);

CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254),
    segmento VARCHAR(100),
    consultor_id BIGINT,
    lote_id BIGINT REFERENCES upload_lote(id),
    codigo_cliente VARCHAR(50) NOT NULL,
    nome_cliente VARCHAR(200) NOT NULL,
    consultor VARCHAR(120) NOT NULL,
    nivel_cliente VARCHAR(20) NOT NULL,
    faturamento_anual NUMERIC(18, 2) NOT NULL,
    cidade VARCHAR(120),
    uf VARCHAR(10),
    data_contratacao DATE,
    mes_contratacao VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS contrato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inicio DATE,
    data_fim DATE,
    valor NUMERIC(18, 2),
    cliente_id BIGINT NOT NULL REFERENCES cliente(id),
    servico_id BIGINT,
    lote_id BIGINT REFERENCES upload_lote(id),
    servicos_contratados TEXT NOT NULL,
    data_contratacao DATE
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
    lote_id BIGINT PRIMARY KEY REFERENCES upload_lote(id) ON DELETE CASCADE,
    gerado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    resultado JSON NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cliente_lote ON cliente(lote_id);
CREATE INDEX IF NOT EXISTS idx_contrato_lote ON contrato(lote_id);
